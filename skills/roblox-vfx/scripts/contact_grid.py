#!/usr/bin/env python3
"""Emit ONE edit-mode Luau script that lays a shipped VFXKit's effects out as a
labelled, phase-frozen contact grid, so a whole kit is judged in a few
screenshots instead of one capture per effect.

DEFECT IT EXISTS FOR (2026-10-08, a creature game build): a 45-effect kit came
back from the asset worker with 41 effects flagged "check" (leaf/petal/snow
sprites stood in by shards, spindles and dots) and no way to look at them short
of 45 separate preview payloads. The skill's verify loop judges ONE recipe at a
time and runs a library recipe, not the module the game will require.

What the emitted script does, all in edit mode:
  * requires a CLONE of the shipped VFXKit ModuleScript (require is cached for
    the Studio session, so an edited kit would otherwise show the old code)
  * builds each named effect on its own anchored cell part, cells on a grid,
    each cell backed by a PALE and a DARK half (additive effects blank on pale
    ground, faint ones vanish on dark - both must read)
  * labels every cell with its name and the sheet id (a freshness witness: a
    stale frame shows the previous sheet's id)
  * bursts are emitted, loops enabled; after --phase seconds every emitter's
    TimeScale goes to 0 so the capture lands on that phase every time
  * returns immediately (execute_luau drops output from a script that yields);
    the freeze runs in a spawned thread
  * prints the camera position and look-at to pass to screen_capture

Usage:
  contact_grid.py --kit ReplicatedStorage.Shared.VFXKit --names A,B,C \
      --sheet s1 --phase 0.3 --out work/grid_s1.luau [--origin 0,400,0] [--cols 3]
  contact_grid.py --clear --out work/grid_clear.luau
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

HEAD = """-- generated by roblox-vfx/scripts/contact_grid.py
local old = workspace:FindFirstChild("__VfxGrid")
if old then old:Destroy() end
"""

BODY = """
local root = Instance.new("Folder")
root.Name = "__VfxGrid"
root.Parent = workspace
local path = {kit}
local node = game
for _, seg in path do node = node:FindFirstChild(seg) end
assert(node, "kit module not found")
local clone = node:Clone()
clone.Parent = root
local K = require(clone)
local names = {names}
local ORIGIN, SP, COLS = Vector3.new({ox}, {oy}, {oz}), {spacing}, {cols}
local handles = {{}}
for i, n in names do
	local col, row = (i - 1) % COLS, math.floor((i - 1) / COLS)
	local pos = ORIGIN + Vector3.new(col * SP, -row * SP, 0)
	for side = 0, 1 do
		local b = Instance.new("Part")
		b.Anchored, b.CanCollide, b.CanQuery = true, false, false
		b.Size = Vector3.new(SP / 2, SP, 0.4)
		b.Position = pos + Vector3.new((side - 0.5) * SP / 2, 0, -SP * 0.45)
		b.Color = if side == 0 then Color3.fromRGB(235, 235, 228) else Color3.fromRGB(46, 62, 50)
		b.Material = Enum.Material.SmoothPlastic
		b.Parent = root
	end
	local p = Instance.new("Part")
	p.Name = n
	p.Anchored, p.CanCollide, p.CanQuery = true, false, false
	p.Transparency = 1
	p.Size = Vector3.one
	p.Position = pos
	p.Parent = root
	local g = Instance.new("BillboardGui")
	g.Size = UDim2.fromOffset(170, 26)
	g.StudsOffsetWorldSpace = Vector3.new(0, SP * 0.42, 0)
	g.AlwaysOnTop = true
	g.Parent = p
	local t = Instance.new("TextLabel")
	t.Size = UDim2.fromScale(1, 1)
	t.BackgroundTransparency = 0.3
	t.BackgroundColor3 = Color3.new(0, 0, 0)
	t.TextColor3 = Color3.new(1, 1, 1)
	t.TextScaled = true
	t.Text = i .. " " .. n .. " [{sheet}]"
	t.Parent = g
	local ok, h = pcall(K.build, n, p, {{}})
	if ok then
		handles[n] = h
		pcall(h.setEnabled, true)
		pcall(h.emit, 1)
	end
end
task.spawn(function()
	task.wait({phase})
	for _, d in root:GetDescendants() do
		if d:IsA("ParticleEmitter") then d.TimeScale = 0 end
	end
end)
local rows = math.ceil(#names / COLS)
local cx = ORIGIN.X + (COLS - 1) * SP / 2
local cy = ORIGIN.Y - (rows - 1) * SP / 2
local dist = math.max(COLS, rows) * SP * 1.25
return string.format("grid {sheet}: %d effects | camera %.1f,%.1f,%.1f look %.1f,%.1f,%.1f",
	#names, cx, cy, ORIGIN.Z + dist, cx, cy, ORIGIN.Z)
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--kit", default="ReplicatedStorage.Shared.VFXKit")
    ap.add_argument("--names", help="comma list, or @file.json (a manifest list with 'name')")
    ap.add_argument("--sheet", default="s1")
    ap.add_argument("--phase", type=float, default=0.3)
    ap.add_argument("--origin", default="0,400,0")
    ap.add_argument("--cols", type=int, default=3)
    ap.add_argument("--spacing", type=float, default=12.0)
    ap.add_argument("--clear", action="store_true")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    if a.clear:
        out.write_text(HEAD + 'return "grid cleared"\n', encoding="utf-8")
        print(f"wrote {out}")
        return 0
    if not a.names:
        raise SystemExit("--names required")
    if a.names.startswith("@"):
        data = json.loads(Path(a.names[1:]).read_text(encoding="utf-8"))
        rows = data if isinstance(data, list) else data.get("effects", [])
        names = [r["name"] for r in rows]
    else:
        names = [n.strip() for n in a.names.split(",") if n.strip()]
    ox, oy, oz = (float(x) for x in a.origin.split(","))
    lua = HEAD + BODY.format(
        kit="{" + ", ".join(f'"{s}"' for s in a.kit.split(".")) + "}",
        names="{" + ", ".join(f'"{n}"' for n in names) + "}",
        ox=ox, oy=oy, oz=oz, spacing=a.spacing, cols=a.cols, sheet=a.sheet, phase=a.phase,
    )
    out.write_text(lua, encoding="utf-8")
    print(f"wrote {out}: {len(names)} effects, ~{math.ceil(len(names) / a.cols)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
