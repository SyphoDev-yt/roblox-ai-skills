#!/usr/bin/env python3
"""Recipe JSON -> a self-contained Luau ModuleScript.

The recipes are the single source of truth. This emitter and the live Studio
builder read the SAME files, so what you tuned in Studio and what ships cannot
disagree about a value.
"""
import json
import os
import pathlib
import sys

def default_lib() -> pathlib.Path:
    """Your own recipe folder: --lib, or the ROBLOX_VFX_LIB env var (see LOCAL.md).

    No effects ship with this skill, so there is no built-in library to fall back
    to. If the library folder has a recipes/ subfolder, that is what is used."""
    v = os.environ.get("ROBLOX_VFX_LIB")
    if not v and (pathlib.Path.home() / "Roblox-VFX-Library").is_dir():
        v = str(pathlib.Path.home() / "Roblox-VFX-Library")  # the setup skill's default
    if not v:
        raise SystemExit("no recipe library given: pass --lib <your VFX library folder> "
                         "or set ROBLOX_VFX_LIB (the path is in LOCAL.md)")
    p = pathlib.Path(v).expanduser()
    return p / "recipes" if (p / "recipes").is_dir() else p


COMPACT = False  # set by --compact: one line per table, same data


def lua(v, ind=0):
    p = "\t" * ind
    if COMPACT and isinstance(v, dict):
        return "{" + ", ".join(
            "%s = %s" % (k if k.isidentifier() else '["%s"]' % k, lua(val)) for k, val in v.items()) + "}"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return repr(round(v, 6))
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "{" + ", ".join(lua(x, ind) for x in v) + "}"
    if isinstance(v, dict):
        parts = []
        for k, val in v.items():
            key = k if k.isidentifier() else '["%s"]' % k
            parts.append("%s\t%s = %s" % (p, key, lua(val, ind + 1)))
        return "{\n" + ",\n".join(parts) + "\n" + p + "}"
    if v is None:
        return "nil"
    raise TypeError(type(v))


HEAD = r'''--# selene: allow(multiple_statements, shadowing, unused_variable)
-- GENERATED by roblox-vfx/scripts/emit_luau.py. Do not hand-edit.
-- (The selene line above: a generated file is linted as generated. A real
-- project's selene gate failed on this file's one-line ifs.)
-- Edit the recipe JSON and regenerate, or tune live in Studio and harvest back.
local VFXKit = {}

local function dec(v)
	if type(v) ~= "table" then return v end
	if v.Enum then
		local cls, item = string.match(v.Enum, "^([%w_]+)%.([%w_]+)$")
		return Enum[cls][item]
	elseif v.Vector3 then return Vector3.new(v.Vector3[1], v.Vector3[2], v.Vector3[3])
	elseif v.Vector2 then return Vector2.new(v.Vector2[1], v.Vector2[2])
	elseif v.Color3 then return Color3.new(v.Color3[1], v.Color3[2], v.Color3[3])
	elseif v.NumberRange then return NumberRange.new(v.NumberRange[1], v.NumberRange[2])
	elseif v.NumberSequence then
		local kp = {}
		for _, k in ipairs(v.NumberSequence) do
			table.insert(kp, NumberSequenceKeypoint.new(k[1], k[2], k[3] or 0))
		end
		return NumberSequence.new(kp)
	elseif v.ColorSequence then
		local kp = {}
		for _, k in ipairs(v.ColorSequence) do
			table.insert(kp, ColorSequenceKeypoint.new(k[1], Color3.new(k[2][1], k[2][2], k[2][3])))
		end
		return ColorSequence.new(kp)
	end
	return nil
end

local function scaleSeq(seq, k)
	local kp = {}
	for _, p in ipairs(seq.Keypoints) do
		table.insert(kp, NumberSequenceKeypoint.new(p.Time, p.Value * k, p.Envelope * k))
	end
	return NumberSequence.new(kp)
end

-- Tint keeps the LUMINANCE ramp and replaces only the hue. A flat colour swap
-- destroys the bright-core-to-dark-tail arc, which is the thing that reads as fire.
local function tintSeq(seq, c)
	local kp = {}
	for _, p in ipairs(seq.Keypoints) do
		local lum = 0.2126 * p.Value.R + 0.7152 * p.Value.G + 0.0722 * p.Value.B
		table.insert(kp, ColorSequenceKeypoint.new(p.Time, Color3.new(
			math.clamp(c.R * lum * 1.6, 0, 1),
			math.clamp(c.G * lum * 1.6, 0, 1),
			math.clamp(c.B * lum * 1.6, 0, 1))))
	end
	return ColorSequence.new(kp)
end

--[[
	VFXKit.build(recipeName, targetPart, opts) -> handle

	targetPart MUST be a BasePart. An Attachment parented to a Model or a Folder
	has no world position, so the effect builds silently at the world origin and
	looks like it simply did not fire.

	opts = { scale, tint (Color3), lifetime_mul, rate_mul, offset (Vector3), suffix }
	handle = { emit(mult), setEnabled(bool), destroy() }
]]
function VFXKit.build(name, target, opts)
	opts = opts or {}
	local recipe = VFXKit.Recipes[name]
	assert(recipe, "roblox-vfx: no recipe named " .. tostring(name))
	assert(typeof(target) == "Instance" and target:IsA("BasePart"),
		"roblox-vfx: build target must be a BasePart, got "
		.. tostring(target and target.ClassName))

	local scale = opts.scale or 1
	local tag = name .. (opts.suffix or "")
	local base = opts.offset or Vector3.new(0, 0, 0)

	for _, c in ipairs(target:GetChildren()) do
		if c:IsA("Attachment") and c:GetAttribute("VFXTag") == tag then c:Destroy() end
	end

	local emitters, lights, ribbons = {}, {}, {}
	for _, layer in ipairs(recipe.layers) do
		local att = Instance.new("Attachment")
		att.Name = tag .. "_" .. layer.name
		att:SetAttribute("VFXTag", tag)
		att.Position = base + Vector3.new(
			layer.offset[1] * scale, layer.offset[2] * scale, layer.offset[3] * scale)
		att.Parent = target

		local inst = Instance.new(layer.class)
		inst.Name = layer.name
		for k, v in pairs(layer.props) do
			local d = dec(v)
			if d ~= nil then pcall(function() inst[k] = d end) end
		end

		if scale ~= 1 then
			pcall(function() inst.Size = scaleSeq(inst.Size, scale) end)
			pcall(function() inst.Speed = NumberRange.new(inst.Speed.Min * scale, inst.Speed.Max * scale) end)
			pcall(function() inst.Acceleration = inst.Acceleration * scale end)
			pcall(function() inst.Range = inst.Range * scale end)
		end
		if opts.tint then pcall(function() inst.Color = tintSeq(inst.Color, opts.tint) end) end
		if opts.lifetime_mul then
			pcall(function()
				inst.Lifetime = NumberRange.new(
					inst.Lifetime.Min * opts.lifetime_mul, inst.Lifetime.Max * opts.lifetime_mul)
			end)
		end
		if opts.rate_mul then pcall(function() inst.Rate = inst.Rate * opts.rate_mul end) end

		local em = layer.emit or {}
		inst:SetAttribute("EmitMode", em.mode or "continuous")
		inst:SetAttribute("VFXTag", tag)
		if em.count then inst:SetAttribute("EmitCount", math.max(1, math.floor(em.count * scale))) end
		if em.seconds then inst:SetAttribute("PulseSeconds", em.seconds) end
		if em.from then inst:SetAttribute("PulseFrom", em.from * scale) end

		-- A burst layer must never also stream, or the effect never stops.
		if em.mode == "burst" then pcall(function() inst.Rate = 0 end) end
		if inst:IsA("PointLight") and em.mode == "pulse" then inst.Brightness = 0 end

		-- A Beam/Trail is STRUCTURE, not values: without both attachments wired it
		-- builds fine, passes every check, and draws absolutely nothing.
		if (inst:IsA("Trail") or inst:IsA("Beam")) and layer.endpoints then
			local eps = {}
			for i, e in ipairs(layer.endpoints) do
				local ea = Instance.new("Attachment")
				ea.Name = tag .. "_" .. layer.name .. "_A" .. i
				ea:SetAttribute("VFXTag", tag)
				ea.Position = base + Vector3.new(
					e.offset[1] * scale, e.offset[2] * scale, e.offset[3] * scale)
				ea.Parent = target
				eps[i] = ea
			end
			inst.Attachment0, inst.Attachment1 = eps[1], eps[2]
		end

		inst.Parent = att
		if inst:IsA("ParticleEmitter") then
			table.insert(emitters, inst)
		elseif inst:IsA("PointLight") then
			table.insert(lights, inst)
		elseif inst:IsA("Trail") or inst:IsA("Beam") then
			table.insert(ribbons, inst)
		end
	end

	local handle = {}

	function handle.emit(mult)
		mult = mult or 1
		for _, e in ipairs(emitters) do
			if e:GetAttribute("EmitMode") == "burst" then
				e:Emit(math.max(1, math.floor((e:GetAttribute("EmitCount") or 1) * mult)))
			end
		end
		for _, l in ipairs(lights) do
			if l:GetAttribute("EmitMode") == "pulse" then
				local peak = (l:GetAttribute("PulseFrom") or 6) * mult
				local secs = l:GetAttribute("PulseSeconds") or 0.25
				l.Brightness = peak
				task.spawn(function()
					local t0 = os.clock()
					while l.Parent do
						local a = (os.clock() - t0) / secs
						if a >= 1 then break end
						l.Brightness = peak * (1 - a) * (1 - a)
						task.wait()
					end
					if l.Parent then l.Brightness = 0 end
				end)
			end
		end
	end

	function handle.setEnabled(on)
		for _, e in ipairs(emitters) do
			if e:GetAttribute("EmitMode") == "continuous" then e.Enabled = on end
		end
		for _, l in ipairs(lights) do
			if l:GetAttribute("EmitMode") == "constant" then l.Enabled = on end
		end
		for _, r in ipairs(ribbons) do
			if r:GetAttribute("EmitMode") ~= "burst" then r.Enabled = on end
		end
	end

	function handle.destroy()
		for _, c in ipairs(target:GetChildren()) do
			if c:IsA("Attachment") and c:GetAttribute("VFXTag") == tag then c:Destroy() end
		end
	end

	handle.emitters, handle.lights, handle.ribbons, handle.tag = emitters, lights, ribbons, tag
	return handle
end

'''


def main():
    import argparse
    ap = argparse.ArgumentParser()
    # Your library lives outside the skill folder. --lib or ROBLOX_VFX_LIB.
    ap.add_argument("--lib", default=None, help="recipe dir (default: $ROBLOX_VFX_LIB)")
    ap.add_argument("out", nargs="?", default=None, help="output .lua path")
    # 2026-10-08 (a creature game): 45 effects inlined blew past Roblox's 200,000-char
    # Source cap (trap 19) - a file that size installs as NOTHING ("Unable to assign
    # property Source") while every offline gate stays green. --compact writes each
    # table on one line (identical data, ~half the size); the guard refuses to write
    # an oversize module unless --allow-oversize.
    ap.add_argument("--compact", action="store_true", help="one line per table (exclude the file from stylua)")
    ap.add_argument("--nocheck", action="store_true", help="prepend --!nocheck (project .luaurc is strict)")
    ap.add_argument("--allow-oversize", action="store_true")
    # 2026-10-09 (a 143-recipe roster ~ 560K chars): one module cannot
    # hold them (trap 19). --data-dir NAME writes the recipe data as chunk modules
    # in a SIBLING folder <out dir>/NAME/Recipes<k>.luau, each under --chunk-chars,
    # and the main module merges them into VFXKit.Recipes at require time. Sibling,
    # not an init.luau folder module: Lune 0.8 resolves "./x" from init.luau against
    # the PARENT directory, so a folder module loads in Studio and breaks offline checks.
    ap.add_argument("--data-dir", default=None, help="split recipe data into sibling chunk modules")
    ap.add_argument("--chunk-chars", type=int, default=180000)
    a = ap.parse_args()
    global COMPACT
    COMPACT = a.compact
    lib = pathlib.Path(a.lib).resolve() if a.lib else default_lib()

    recipes = {}
    for p in sorted(lib.glob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        recipes[d["name"]] = {
            "name": d["name"],
            "duration": d.get("duration", 2),
            "texture_portable": d.get("texture_portable", False),
            "layers": [
                {
                    "name": L["name"],
                    "class": L["class"],
                    "offset": L["offset"],
                    "emit": {k: v for k, v in (L.get("emit") or {}).items() if v is not None},
                    "props": L["props"],
                    # Beam/Trail endpoints are structure. Dropping them here was
                    # a silent way to ship a ribbon that draws nothing.
                    **({"endpoints": L["endpoints"]} if L.get("endpoints") else {}),
                }
                for L in d["layers"]
            ],
        }
    if a.data_dir:
        return emit_split(a, recipes)
    body = HEAD + "VFXKit.Recipes = " + lua(recipes) + "\n\nreturn VFXKit\n"
    if a.nocheck:
        body = "--!nocheck\n" + body
    if len(body) >= 200000 and not a.allow_oversize:
        print("FAIL %d chars >= 200000: Roblox will refuse this Source (trap 19). "
              "Use --compact, curate fewer layers, or split." % len(body))
        sys.exit(1)
    out = pathlib.Path(a.out) if a.out else pathlib.Path("references/VFXKit.lua")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    print("%s %d chars, recipes: %s" % (out, len(body), ", ".join(recipes)))


CHUNK_HEAD = ("--!nocheck\n--# selene: allow(multiple_statements, shadowing, unused_variable)\n"
              "-- GENERATED by roblox-vfx/scripts/emit_luau.py --data-dir. Do not hand-edit.\n"
              "-- Recipe data chunk %d of %d for VFXKit (split under Roblox's 200,000-char Source cap).\n")


def emit_split(a, recipes):
    out = pathlib.Path(a.out)
    ddir = out.parent / a.data_dir
    chunks, cur, size = [], {}, 0
    for name, r in recipes.items():
        n = len(lua({name: r}))
        if cur and size + n > a.chunk_chars:
            chunks.append(cur)
            cur, size = {}, 0
        cur[name] = r
        size += n
    if cur:
        chunks.append(cur)
    ddir.mkdir(parents=True, exist_ok=True)
    for old in ddir.glob("Recipes*.luau"):
        old.unlink()
    for k, c in enumerate(chunks, 1):
        body = CHUNK_HEAD % (k, len(chunks)) + "return " + lua(c) + "\n"
        if len(body) >= 200000:
            print("FAIL chunk %d is %d chars >= 200000" % (k, len(body)))
            sys.exit(1)
        (ddir / ("Recipes%d.luau" % k)).write_text(body, encoding="utf-8", newline="\n")
    loader = (
        "VFXKit.Recipes = {}\n"
        "-- data chunks live in the sibling folder %s (Roblox: script.Parent.%s; Lune: a relative path)\n"
        "for k = 1, %d do\n"
        "\tlocal chunk\n"
        "\tif script ~= nil then\n"
        "\t\tchunk = require(script.Parent:WaitForChild(\"%s\"):WaitForChild(\"Recipes\" .. k))\n"
        "\telse\n"
        "\t\t-- selene: allow(incorrect_standard_library_use)\n"
        "\t\tchunk = require(\"./%s/Recipes\" .. k)\n"
        "\tend\n"
        "\tfor name, r in pairs(chunk) do\n"
        "\t\tVFXKit.Recipes[name] = r\n"
        "\tend\n"
        "end\n"
    ) % (a.data_dir, a.data_dir, len(chunks), a.data_dir, a.data_dir)
    body = HEAD + loader + "\nreturn VFXKit\n"
    if a.nocheck:
        body = "--!nocheck\n" + body
    out.write_text(body, encoding="utf-8", newline="\n")
    sizes = ", ".join(str((ddir / ("Recipes%d.luau" % k)).stat().st_size) for k in range(1, len(chunks) + 1))
    print("%s %d chars + %d chunk(s) in %s (%s chars), %d recipes" % (out, len(body), len(chunks), ddir, sizes, len(recipes)))


if __name__ == "__main__":
    main()
